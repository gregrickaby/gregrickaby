import { existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Writes the source of `.generated/demos.ts`: one import per post folder
 * under `components/islands/demos/` that has a `registry.ts`, keyed by the
 * folder name, which is the post's slug. Next can only bundle imports it can
 * see at build time, so the list is generated, not read at runtime.
 *
 * @param demosDir - The `components/islands/demos` folder.
 * @returns TypeScript source for the registry.
 */
export function buildDemoRegistry(demosDir: string): string {
  const slugs = existsSync(demosDir)
    ? readdirSync(demosDir)
        .filter((slug) => existsSync(join(demosDir, slug, 'registry.ts')))
        .sort()
    : []
  const imports = slugs.map(
    (slug, i) => `import { DEMOS as demos${i} } from '@/components/islands/demos/${slug}/registry'`,
  )
  const entries = slugs.map((slug, i) => `  '${slug}': demos${i},`)
  return [
    '// Generated by scripts/build-content.ts. Do not edit.',
    "import type { DemoEntry } from '@/lib/types'",
    ...imports,
    '',
    "/** Each post's demos, keyed by slug. */",
    'export const POST_DEMOS: Record<string, Record<string, DemoEntry>> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
}
